//! `src/cron.ts` and `src/sources.ts`: what `serve` runs beside its routes
//! (PRD resolved q78, grammar 13.4, 13.5, 14.4, Decision D162).
//!
//! Both are **constants**, emitted verbatim under the header for the reasons
//! [`super::runtime`] is one: what differs between two projects is the table
//! [`super::trigger`] emits — the schedules, the event triggers and the active
//! target's `event_sources:` — and the scheduler and the consumers over it are
//! the same code in every build.
//!
//! `src/cron.ts` is the evaluator a `schedule` trigger's `cron:` is read by. It
//! has **no imports**, like `src/cel.ts`, because a shared conformance corpus
//! (`tests/fixtures/cron-conformance/`) runs against it and against
//! [`crate::cron`]: the grammar `validate` holds an expression to and the one
//! `serve` evaluates it by are kept one reading by that corpus, the way CEL's
//! two interpreters are.
//!
//! `src/sources.ts` is the scheduler and the `kind: command` consumer. It hands
//! every tick and every event to `src/serve.ts`'s admission — the one function
//! every trigger kind's start passes through — so nothing here decides whether
//! an execution starts.

use crate::ir::Ir;

/// The evaluator's source, carried in the compiler and emitted verbatim.
const CRON: &str = include_str!("js/cron.ts");

/// The scheduler and the consumers, carried and emitted the same way.
const SOURCES: &str = include_str!("js/sources.ts");

/// `src/cron.ts`.
#[must_use]
pub fn cron(ir: &Ir) -> super::GeneratedFile {
    let mut contents = super::header(ir, "// ");
    contents.push_str(CRON);
    super::GeneratedFile {
        path: "src/cron.ts".to_string(),
        contents,
    }
}

/// `src/sources.ts`.
#[must_use]
pub fn module(ir: &Ir) -> super::GeneratedFile {
    let mut contents = super::header(ir, "// ");
    contents.push_str(SOURCES);
    super::GeneratedFile {
        path: "src/sources.ts".to_string(),
        contents,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ast::deploy::EventSourceKind;
    use crate::codegen::test_support::ir_of;

    #[test]
    fn both_modules_are_emitted_verbatim_under_the_header() {
        let ir = ir_of("version: \"0.1\"\n");
        let cron = cron(&ir).contents;
        assert!(cron.starts_with("// This file was generated by agent-compose"));
        assert!(cron.ends_with(CRON));
        let sources = module(&ir).contents;
        assert!(sources.ends_with(SOURCES));
    }

    /// The evaluator stands alone, so the conformance runner can import it
    /// without the runtime — `src/cel.ts`'s posture.
    #[test]
    fn the_evaluator_imports_nothing() {
        assert!(
            !CRON.lines().any(|line| line.starts_with("import ")),
            "`src/cron.ts` is run by the conformance corpus on its own, so it imports nothing"
        );
    }

    /// The kinds `serve` runs a consumer for are the ones the compiler says
    /// are implemented (`EventSourceKind::implemented`): a release that grew a
    /// consumer in one place and not the other would refuse a source it runs,
    /// or run one it refuses.
    #[test]
    fn the_runtime_implements_exactly_the_kinds_the_compiler_says_it_does() {
        let emitted = crate::codegen::trigger::module(&ir_of("version: \"0.1\"\n")).contents;
        let line = emitted
            .lines()
            .find(|line| line.starts_with("export const IMPLEMENTED_SOURCE_KINDS"))
            .expect("the trigger table states the implemented kinds");
        for kind in EventSourceKind::ALL {
            assert_eq!(
                line.contains(&format!("\"{}\"", kind.as_str())),
                kind.implemented(),
                "`{}`: {line}",
                kind.as_str()
            );
        }
    }

    /// The variable a program reads its checkpoint from is the one the grammar
    /// and the topic name.
    #[test]
    fn the_checkpoint_reaches_the_program_by_the_documented_name() {
        assert!(SOURCES.contains("CHECKPOINT_VARIABLE = \"AGENT_COMPOSE_CHECKPOINT\""));
        assert!(
            SOURCES.contains("detached: true"),
            "the program runs in a group of its own"
        );
    }
}
